"""
Generates a synthetic but realistically shaped MSBuild solution, and measures what a rebuild
costs on it today.

Why synthetic: the shape that matters for incrementality is the dependency graph, specifically the
*depth* of the downstream cone below a leaf. A generated graph lets that be varied and stated
exactly, so a reviewer can check the claim against the shape rather than taking a proprietary
repository on trust. The generated projects contain enough real code to make compilation take
measurable time.

The measurement this produces is the "before" column of the macOS evidence campaign, and it needs
no sandbox, no entitlement and no BuildXL. It establishes the size of the prize.

The specific asymmetry being measured is this:

  MSBuild decides whether to rebuild a project by comparing timestamps. If project A is rebuilt,
  A.dll gets a new timestamp, so every project downstream of A is rebuilt too -- even when A.dll is
  byte-for-byte identical to what it was before.

  A content-addressed build engine compares content. If A.dll is unchanged, everything downstream
  is a cache hit.

A comment-only edit makes the two diverge maximally: the source changed, so A must be rebuilt in
both systems, but A.dll does not change, so the entire downstream cone is avoidable work. This
script measures how much work that actually is.

Usage:
    python3 generate_msbuild_demo.py --out /tmp/demo --width 8 --depth 5
    python3 generate_msbuild_demo.py --out /tmp/demo --measure --repeats 5
"""

import argparse
import json
import os
import platform
import shutil
import statistics
import subprocess
import sys
import time

PROJECT_TEMPLATE = """<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>{tfm}</TargetFramework>
    <Nullable>disable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
    <!-- Deterministic output is what makes the comment-only scenario meaningful: without it the
         assembly changes on every build for reasons unrelated to the source edit. -->
    <Deterministic>true</Deterministic>
  </PropertyGroup>
{refs}</Project>
"""

CLASS_TEMPLATE = """// Copyright (c) Microsoft Corporation.
// Licensed under the MIT License.
// Generated by generate_msbuild_demo.py -- not intended to be edited by hand.

namespace {ns}
{{
    public static class Widget{index}
    {{
        public const string Marker = "BXL_BENCH_0";

        public static long Compute(long seed)
        {{
            long acc = seed;
{body}
            return acc;
        }}
    }}
}}
"""


def make_body(lines):
    """Enough arithmetic that compilation is not instantaneous, but fully deterministic."""
    out = []
    for i in range(lines):
        out.append(f"            acc = unchecked(acc * 31 + {i * 2654435761 % 1000003});")
    return "\n".join(out)


def generate(root, width, depth, classes_per_project, lines_per_class, tfm):
    """Build a layered graph: `depth` layers of `width` projects.

    Every project in layer N references every project in layer N-1. That fan-in is what makes the
    downstream cone of a single leaf large, which is precisely the cost being measured.
    """
    if os.path.isdir(root):
        shutil.rmtree(root)
    os.makedirs(root)

    layers = []
    for layer in range(depth):
        names = [f"Layer{layer}.Project{i}" for i in range(width)]
        layers.append(names)

    for layer, names in enumerate(layers):
        for name in names:
            proj_dir = os.path.join(root, name)
            os.makedirs(proj_dir, exist_ok=True)

            if layer == 0:
                refs = ""
            else:
                items = "".join(
                    f'    <ProjectReference Include="..\\{dep}\\{dep}.csproj" />\n'
                    for dep in layers[layer - 1]
                )
                refs = f"  <ItemGroup>\n{items}  </ItemGroup>\n"

            with open(os.path.join(proj_dir, f"{name}.csproj"), "w") as handle:
                handle.write(PROJECT_TEMPLATE.format(tfm=tfm, refs=refs))

            for index in range(classes_per_project):
                with open(os.path.join(proj_dir, f"Widget{index}.cs"), "w") as handle:
                    handle.write(
                        CLASS_TEMPLATE.format(
                            ns=name.replace(".", "_"),
                            index=index,
                            body=make_body(lines_per_class),
                        )
                    )

    # A single aggregator project builds everything without needing a .sln, which keeps the demo
    # independent of solution-format churn. It must be a .csproj: MSBuild picks the language
    # targets from the file extension, and a bare .proj never imports Microsoft.CSharp.targets,
    # so ordinary targets like CreateManifestResourceNames would not exist.
    all_projects = [n for names in layers for n in names]
    refs = "".join(
        f'    <ProjectReference Include="{n}\\{n}.csproj" />\n' for n in all_projects
    )
    with open(os.path.join(root, "Build.csproj"), "w") as handle:
        handle.write(
            "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
            "  <PropertyGroup>\n"
            f"    <TargetFramework>{tfm}</TargetFramework>\n"
            "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
            "  </PropertyGroup>\n"
            f"  <ItemGroup>\n{refs}  </ItemGroup>\n"
            "</Project>\n"
        )

    leaf = os.path.join(root, layers[0][0], "Widget0.cs")
    manifest = {
        "root": os.path.abspath(root),
        "width": width,
        "depth": depth,
        "projects": len(all_projects),
        "classes_per_project": classes_per_project,
        "lines_per_class": lines_per_class,
        "target_framework": tfm,
        "leaf_source_file": os.path.abspath(leaf),
        "downstream_of_leaf": (depth - 1) * width,
        "entry_point": os.path.abspath(os.path.join(root, "Build.csproj")),
    }
    with open(os.path.join(root, "demo-manifest.json"), "w") as handle:
        json.dump(manifest, handle, indent=2)
    return manifest


# --------------------------------------------------------------------------------------------
# Measurement of the prior state (plain MSBuild, no BuildXL, no sandbox)
# --------------------------------------------------------------------------------------------


def dotnet_env():
    env = dict(os.environ)
    root = env.get("DOTNET_ROOT") or os.path.expanduser("~/.dotnet")
    if os.path.isdir(root):
        env["DOTNET_ROOT"] = root
        env["PATH"] = root + os.pathsep + env.get("PATH", "")
    # Telemetry and the first-run banner would otherwise pollute the first timing.
    env["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1"
    env["DOTNET_NOLOGO"] = "1"
    env["DOTNET_SKIP_FIRST_TIME_EXPERIENCE"] = "1"
    return env


def build_once(manifest, extra=None):
    cmd = ["dotnet", "build", manifest["entry_point"], "-nologo", "-v", "q"]
    if extra:
        cmd += extra
    started = time.monotonic()
    completed = subprocess.run(
        cmd, capture_output=True, text=True, errors="replace", env=dotnet_env()
    )
    elapsed = time.monotonic() - started
    return elapsed, completed


def primary_outputs(root, manifest):
    """Map project name -> path of that project's own output assembly.

    Only primary outputs are counted. Every project's bin directory also contains *copies* of its
    transitive dependencies, so a naive directory walk reports far more assemblies than there are
    projects and makes the result uninterpretable.
    """
    paths = {}
    for layer in range(manifest["depth"]):
        for i in range(manifest["width"]):
            name = f"Layer{layer}.Project{i}"
            bin_dir = os.path.join(root, name, "bin")
            if not os.path.isdir(bin_dir):
                continue
            for dirpath, _dirnames, filenames in os.walk(bin_dir):
                if f"{name}.dll" in filenames:
                    paths[name] = os.path.join(dirpath, f"{name}.dll")
                    break
    return paths


def count_rebuilt(root, manifest, since):
    """Projects whose own output assembly was rewritten after `since`.

    This measures "how much did MSBuild actually redo" independently of log verbosity or MSBuild
    version.
    """
    rebuilt = []
    for name, path in primary_outputs(root, manifest).items():
        try:
            if os.path.getmtime(path) > since:
                rebuilt.append(name)
        except OSError:
            pass
    return rebuilt


def hash_outputs(root, manifest):
    """Content hash of each project's own output assembly, so "did the output actually change"
    can be answered rather than assumed."""
    import hashlib

    digests = {}
    for name, path in primary_outputs(root, manifest).items():
        try:
            with open(path, "rb") as handle:
                digests[name] = hashlib.sha256(handle.read()).hexdigest()
        except OSError:
            pass
    return digests


def measure(manifest, repeats):
    root = manifest["root"]
    leaf = manifest["leaf_source_file"]
    results = {
        "manifest": manifest,
        "environment": {
            "os": platform.system(),
            "release": platform.release(),
            "machine": platform.machine(),
            "cpu_count": os.cpu_count(),
        },
        "scenarios": [],
    }

    dotnet_version = subprocess.run(
        ["dotnet", "--version"], capture_output=True, text=True, env=dotnet_env()
    ).stdout.strip()
    results["environment"]["dotnet"] = dotnet_version

    def record(name, note, samples, rebuilt_counts, extra=None):
        entry = {
            "scenario": name,
            "note": note,
            "wall_seconds_median": round(statistics.median(samples), 3),
            "wall_seconds_min": round(min(samples), 3),
            "wall_seconds_max": round(max(samples), 3),
            "n": len(samples),
            "assemblies_rebuilt_median": statistics.median(rebuilt_counts) if rebuilt_counts else None,
        }
        if extra:
            entry.update(extra)
        results["scenarios"].append(entry)
        print(
            f"  {name:22s} median {entry['wall_seconds_median']:7.2f}s  "
            f"(min {entry['wall_seconds_min']:.2f} max {entry['wall_seconds_max']:.2f})  "
            f"assemblies rebuilt: {entry['assemblies_rebuilt_median']}",
            flush=True,
        )
        return entry

    with open(leaf) as handle:
        pristine = handle.read()

    # --- cold ---------------------------------------------------------------------------------
    print("\nprior state: plain MSBuild on this machine\n")
    cold_samples = []
    for _ in range(repeats):
        for sub in ("bin", "obj"):
            for dirpath, dirnames, _f in os.walk(root):
                if sub in dirnames:
                    shutil.rmtree(os.path.join(dirpath, sub), ignore_errors=True)
        elapsed, completed = build_once(manifest)
        if completed.returncode != 0:
            print(completed.stdout[-4000:], file=sys.stderr)
            print(completed.stderr[-2000:], file=sys.stderr)
            raise SystemExit("cold build failed")
        cold_samples.append(elapsed)
    record("cold", "empty output tree", cold_samples, [manifest["projects"]])

    # --- no-op --------------------------------------------------------------------------------
    noop_samples, noop_rebuilt = [], []
    for _ in range(repeats):
        mark = time.time()
        time.sleep(0.05)
        elapsed, _ = build_once(manifest)
        noop_samples.append(elapsed)
        noop_rebuilt.append(len(count_rebuilt(root, manifest, mark)))
    record("no-op rebuild", "nothing changed", noop_samples, noop_rebuilt)

    # --- comment-only -------------------------------------------------------------------------
    # The decisive scenario. The source changes, so the leaf must be recompiled, but the emitted
    # assembly is unchanged, so every downstream project is avoidable work.
    comment_samples, comment_rebuilt, wasted = [], [], []
    for i in range(repeats):
        before = hash_outputs(root, manifest)
        with open(leaf, "w") as handle:
            handle.write(pristine.rstrip("\n") + f"\n// demo comment mutation {i}\n")
        mark = time.time()
        time.sleep(0.05)
        elapsed, _ = build_once(manifest)
        comment_samples.append(elapsed)
        rebuilt = count_rebuilt(root, manifest, mark)
        comment_rebuilt.append(len(rebuilt))
        after = hash_outputs(root, manifest)
        # Of the projects MSBuild recompiled, how many produced byte-identical output? That is
        # precisely the work a content-addressed cache would have skipped.
        wasted.append(
            sum(1 for name in rebuilt if before.get(name) and before[name] == after.get(name))
        )
    entry = record(
        "comment-only change",
        "source changed, emitted assemblies unchanged",
        comment_samples,
        comment_rebuilt,
        {"rebuilt_but_byte_identical_median": statistics.median(wasted)},
    )
    print(
        f"    -> {entry['rebuilt_but_byte_identical_median']:.0f} of "
        f"{entry['assemblies_rebuilt_median']:.0f} recompiled projects produced byte-identical "
        f"output: avoidable work"
    )

    # --- observable ---------------------------------------------------------------------------
    observable_samples, observable_rebuilt = [], []
    for i in range(repeats):
        with open(leaf, "w") as handle:
            handle.write(pristine.replace("BXL_BENCH_0", f"BXL_BENCH_{i + 1}"))
        mark = time.time()
        time.sleep(0.05)
        elapsed, _ = build_once(manifest)
        observable_samples.append(elapsed)
        observable_rebuilt.append(len(count_rebuilt(root, manifest, mark)))
    record(
        "observable change",
        "leaf constant changed, must propagate",
        observable_samples,
        observable_rebuilt,
    )

    # --- timestamp churn with identical content -----------------------------------------------
    # This is the scenario that separates timestamp-based incrementality from content-addressed
    # caching, and it is not a contrived one: `git checkout` of another branch and back, a fresh
    # clone, and a CI agent with a clean workspace all produce source files whose content is
    # identical to something already built but whose mtimes are new. MSBuild compares timestamps,
    # so it must rebuild. A content-addressed cache sees the same inputs and skips everything.
    touch_samples, touch_rebuilt, touch_identical = [], [], []
    for _ in range(repeats):
        before = hash_outputs(root, manifest)
        now = time.time() + 1
        for dirpath, _dirnames, filenames in os.walk(root):
            if f"{os.sep}bin" in dirpath or f"{os.sep}obj" in dirpath:
                continue
            for name in filenames:
                if name.endswith((".cs", ".csproj")):
                    os.utime(os.path.join(dirpath, name), (now, now))
        mark = time.time()
        time.sleep(0.05)
        elapsed, _ = build_once(manifest)
        touch_samples.append(elapsed)
        rebuilt = count_rebuilt(root, manifest, mark)
        touch_rebuilt.append(len(rebuilt))
        after = hash_outputs(root, manifest)
        touch_identical.append(
            sum(1 for name in rebuilt if before.get(name) and before[name] == after.get(name))
        )
    entry = record(
        "timestamp churn",
        "content identical, mtimes new (branch switch / fresh clone / CI agent)",
        touch_samples,
        touch_rebuilt,
        {"rebuilt_but_byte_identical_median": statistics.median(touch_identical)},
    )
    if entry["assemblies_rebuilt_median"]:
        print(
            f"    -> {entry['rebuilt_but_byte_identical_median']:.0f} of "
            f"{entry['assemblies_rebuilt_median']:.0f} recompiled projects produced "
            f"byte-identical output: entirely avoidable work"
        )

    with open(leaf, "w") as handle:
        handle.write(pristine)

    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True)
    parser.add_argument("--width", type=int, default=8)
    parser.add_argument("--depth", type=int, default=5)
    parser.add_argument("--classes-per-project", type=int, default=6)
    parser.add_argument("--lines-per-class", type=int, default=180)
    parser.add_argument("--tfm", default="net9.0")
    parser.add_argument("--measure", action="store_true", help="Measure the prior state after generating")
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--results", default=None, help="Write measurement JSON here")
    parser.add_argument("--skip-generate", action="store_true")
    args = parser.parse_args()

    if args.skip_generate:
        with open(os.path.join(args.out, "demo-manifest.json")) as handle:
            manifest = json.load(handle)
    else:
        manifest = generate(
            args.out,
            args.width,
            args.depth,
            args.classes_per_project,
            args.lines_per_class,
            args.tfm,
        )
        print(
            f"generated {manifest['projects']} projects "
            f"({args.width} wide x {args.depth} deep), "
            f"{manifest['downstream_of_leaf']} downstream of the leaf, at {manifest['root']}"
        )

    if args.measure:
        results = measure(manifest, args.repeats)
        out = args.results or os.path.join(args.out, "prior-state.json")
        with open(out, "w") as handle:
            json.dump(results, handle, indent=2)
        print(f"\nwrote {out}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
